/** India first, then the most common destinations, then A–Z (as listed above). */
export const COUNTRIES: Country[] = RAW.map(([iso, name, dial]) => ({ iso, name, dial }));

const BY_ISO = new Map(COUNTRIES.map((c) => [c.iso, c]));
export const countryByIso = (iso: string): Country => BY_ISO.get(iso.toUpperCase()) ?? BY_ISO.get("IN")!;

/** Which country a shared code is shown under when parsing a full number. */
const PREFERRED_ISO: Record<string, string> = { "1": "US", "7": "RU", "44": "GB", "61": "AU" };

/** Longest dial code that prefixes `digits` (e.g. "971501234567" → UAE). */
export function countryForDigits(digits: string): Country | null {
  for (let len = 3; len >= 1; len--) {
    const code = digits.slice(0, len);
    const pref = PREFERRED_ISO[code];
    if (pref) return BY_ISO.get(pref)!;
    const hit = COUNTRIES.find((c) => c.dial === code);
    if (hit) return hit;
  }
  return null;
}

